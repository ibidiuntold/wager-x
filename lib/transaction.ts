import { collection, doc, addDoc, updateDoc, getDoc } from 'firebase/firestore';
import type { Transaction } from '@/components/common/wallet/types';
import type { UserData } from '@/types/user.types';

interface CreateWithdrawalParams {
  userId: string;
  autoGeneratedId: string;
  amount: number;
  accountNumber: string;
  bankCode: string;
  bankName: string;
  accountName: string;
  firestore: any;
}

export async function createWithdrawalTransaction(params: CreateWithdrawalParams): Promise<string> {
    const { firestore, ...transactionData } = params;
    
    try {
      // Get current user data first
      const userRef = doc(firestore, 'users', transactionData.userId);
      const userSnap = await getDoc(userRef);
      
      if (!userSnap.exists()) {
        throw new Error('User not found');
      }
  
      const userData = userSnap.data() as UserData;
      const newBalance = Math.max(0, userData.walletBalance - transactionData.amount);
  
      // Create transaction record
      const transactionRef = await addDoc(collection(firestore, 'transactions'), {
        userId: transactionData.autoGeneratedId,
        type: 'withdrawal',
        amount: transactionData.amount,
        date: new Date().toISOString(),
        status: 'pending',
        provider: 'manual',
        reference: `WD${Date.now()}`,
        accountDetails: {
          accountNumber: transactionData.accountNumber,
          bankCode: transactionData.bankCode,
          bankName: transactionData.bankName,
          accountName: transactionData.accountName
        }
      } as Transaction);
  
      // Update user's wallet balance with new value
      await updateDoc(userRef, {
        walletBalance: newBalance,
        lastUpdated: new Date().toISOString(),
        // If this is first withdrawal, save bank details
        ...(userData.bankDetails ? {} : {
          bankDetails: {
            accountNumber: transactionData.accountNumber,
            bankCode: transactionData.bankCode,
            bankName: transactionData.bankName,
            accountName: transactionData.accountName
          }
        })
      });
  
      return transactionRef.id;
    } catch (error) {
      console.error('Error creating withdrawal:', error);
      throw error;
    }
}

export function calculateWithdrawalFee(amount: number): number {
  const withdrawalCharge = Number(process.env.WITHDRAWAL_CHARGE) || 0.5;
  return (amount * withdrawalCharge) / 100;
}

export function formatTransactionStatus(status: Transaction['status']): {
  label: string;
  className: string;
} {
  switch (status) {
    case 'success':
      return {
        label: 'Completed',
        className: 'bg-green-100 text-green-800 dark:bg-green-800 dark:text-green-100'
      };
    case 'pending':
      return {
        label: 'Processing',
        className: 'bg-yellow-100 text-yellow-800 dark:bg-yellow-800 dark:text-yellow-100'
      };
    case 'failed':
      return {
        label: 'Failed',
        className: 'bg-red-100 text-red-800 dark:bg-red-800 dark:text-red-100'
      };
    default:
      return {
        label: status,
        className: 'bg-gray-100 text-gray-800 dark:bg-gray-800 dark:text-gray-100'
      };
  }
}