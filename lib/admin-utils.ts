import { getFirestore, doc, getDoc, setDoc, runTransaction, collection, query, where, getDocs } from 'firebase/firestore';
import { UserProfile } from '@/types/user.types';

const ADMIN_CONFIG_DOC = 'admin_configuration';

interface AdminConfig {
  setupComplete: boolean;
  superAdminEmail: string;
}

export async function isFirstTimeSetup(): Promise<boolean> {
  try {
    const db = getFirestore();
    if (!db) {
      throw new Error('Firestore is not initialized');
    }
    
    const configDoc = await getDoc(doc(db, 'system', ADMIN_CONFIG_DOC));
    return !configDoc.exists();
  } catch (error) {
    console.error('Error checking first time setup:', error);
    throw new Error('Failed to check admin setup status. Please ensure Firebase is properly configured.');
  }
}

export async function setupSuperAdmin(userProfile: UserProfile) {
  try {
    const db = getFirestore();
    if (!db) {
      throw new Error('Firestore is not initialized');
    }
    
    // Check if setup was already done
    const configDoc = await getDoc(doc(db, 'system', ADMIN_CONFIG_DOC));
    if (configDoc.exists()) {
      throw new Error('Admin setup has already been completed');
    }

    // Use a transaction to ensure atomicity
    await runTransaction(db, async (transaction) => {
      // Set user as super admin
      const userRef = doc(db, 'users', userProfile.autoGeneratedId);
      transaction.set(userRef, {
        ...userProfile,
        role: 'admin'
      });

      // Mark setup as complete
      const configRef = doc(db, 'system', ADMIN_CONFIG_DOC);
      transaction.set(configRef, {
        setupComplete: true,
        superAdminEmail: userProfile.email,
        createdAt: new Date().toISOString()
      });
    });

    return true;
  } catch (error) {
    console.error('Error setting up super admin:', error);
    throw new Error('Failed to set up admin account. Please try again.');
  }
}

export async function isUserAdmin(email: string): Promise<boolean> {
  try {
    const db = getFirestore();
    if (!db) {
      throw new Error('Firestore is not initialized');
    }
    
    // Query users by email
    const usersRef = collection(db, 'users');
    const q = query(usersRef, where('email', '==', email));
    const querySnapshot = await getDocs(q);
    
    if (querySnapshot.empty) return false;

    const userData = querySnapshot.docs[0].data() as UserProfile;
    return userData.role === 'admin' || userData.role === 'manager';
  } catch (error) {
    console.error('Error checking admin status:', error);
    throw new Error('Failed to verify admin privileges. Please try again.');
  }
}
