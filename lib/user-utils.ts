import { generateReferralCode } from '@/lib/utils';

const generateUserId = (): string => {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  let id = '';
  for (let i = 0; i < 8; i++) {
    id += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return id;
};

export interface UserProfile {
  autoGeneratedId: string;
  avatarUrl: string;
  createdAt: string;
  email: string;
  emailVerified: boolean;
  firstName: string;
  lastName: string;
  nickname: string;
  dob: string;
  gamePoints: number;
  kycVerified: boolean;
  lastLogin: string;
  mailingSettings: {
    personalBonuses: boolean;
    pushNotifications: boolean;
    smsDistribution: boolean;
    systemMessages: boolean;
  };
  phoneNumber: string | null;
  role: 'user' | 'admin' | 'manager';
  status: 'active' | 'suspended' | 'banned';
  walletBalance: number;
  referralCode: string; // Required field for the referral system
}

export const generateUserProfile = (
  email: string,
  avatarUrl: string,
  phoneNumber: string | null,
  nickname: string,
  registerBonus: number,
  firstName: string = '',
  lastName: string = '',
  dob: string = ''
): UserProfile => {
  const now = new Date().toISOString();
  
  return {
    autoGeneratedId: generateUserId(),
    avatarUrl,
    createdAt: now,
    email,
    emailVerified: false,
    firstName,
    lastName,
    nickname,
    dob,
    gamePoints: 0,
    kycVerified: false,
    lastLogin: now,
    mailingSettings: {
      personalBonuses: true,
      pushNotifications: true,
      smsDistribution: true,
      systemMessages: true
    },
    phoneNumber,
    role: 'user',
    status: 'active',
    walletBalance: 0,
    referralCode: generateReferralCode()
  };
};

export default generateUserProfile;