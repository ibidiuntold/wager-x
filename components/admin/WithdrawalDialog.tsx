import React, { useEffect, useState } from 'react';
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { collection, doc, query, where, orderBy, limit, WithFieldValue, DocumentData } from 'firebase/firestore';
import { Loader2, Printer } from 'lucide-react';
import { PDFDownloadLink } from '@react-pdf/renderer';
import { WithdrawalSlip } from './WithdrawalSlip';
import type { Transaction } from '@/components/common/wallet/types';
import type { UserData } from '@/types/user.types';

interface WithdrawalDialogProps {
  isOpen: boolean;
  onClose: () => void;
  withdrawalData: {
    id: string;
    userId: string;
    amount: number;
    bankName: string;
    accountNumber: string;
    accountName: string;
    reference: string;
  };
  onStatusUpdate: (id: string, status: 'success' | 'failed', reason?: string) => Promise<void>;
}

const FAILURE_REASONS = [
  'Incorrect bank details',
  'Bank network error',
  'Insufficient balance',
  'Suspicious activity',
  'Technical error',
  'Other'
];

const userConverter = {
  toFirestore(user: WithFieldValue<UserData>): DocumentData {
    return user;
  },
  fromFirestore(snapshot: any): UserData {
    const data = snapshot.data();
    return {
      email: data.email,
      autoGeneratedId: data.autoGeneratedId,
      walletBalance: data.walletBalance,
      createdAt: data.createdAt,
      dob: data.dob,
      emailVerified: data.emailVerified,
      firstName: data.firstName,
      lastName: data.lastName,
      gamePoints: data.gamePoints,
      kycVerified: data.kycVerified,
      lastLogin: data.lastLogin,
      lastUpdated: data.lastUpdated,
      mailingSettings: data.mailingSettings,
      nickname: data.nickname,
      phoneNumber: data.phoneNumber,
      role: data.role,
      status: data.status,
      bankDetails: data.bankDetails,
      avatarUrl: data.avatarUrl || '',
      referralCode: data.referralCode || '',
    };
  },
};

const transactionConverter = {
  toFirestore(transaction: WithFieldValue<Transaction>): DocumentData {
    return transaction;
  },
  fromFirestore(snapshot: any): Transaction {
    const data = snapshot.data();
    return {
      userId: data.userId || data.autoGeneratedId,
      type: data.type,
      amount: data.amount,
      date: data.date,
      status: data.status,
      provider: data.provider,
      reference: data.reference,
      bonusAwarded: data.bonusAwarded,
      accountDetails: data.accountDetails,
    };
  },
};

export function WithdrawalDialog({ 
  isOpen, 
  onClose, 
  withdrawalData, 
  onStatusUpdate 
}: WithdrawalDialogProps) {
  // Remove: const firestore = useFirestore();
  const [selectedReason, setSelectedReason] = useState<string>('');
  const [isProcessing, setIsProcessing] = useState(false);

  // Get user data
  const userRef = doc(firestore, 'users', withdrawalData.userId).withConverter(userConverter);
  const { status: userStatus, data: userData } = useFirestoreDocData(userRef);

  // Get user's last 4 transactions
  const transactionsRef = collection(firestore, 'transactions').withConverter(transactionConverter);
  const transactionsQuery = query(
    transactionsRef,
    where('autoGeneratedId', '==', withdrawalData.userId),
    orderBy('date', 'desc'),
    limit(4)
  );
  const { status: transactionsStatus, data: recentTransactions } = useFirestoreCollectionData(transactionsQuery);

  const handleComplete = async () => {
    setIsProcessing(true);
    try {
      await onStatusUpdate(withdrawalData.id, 'success');
      onClose();
    } catch (error) {
      console.error('Error completing withdrawal:', error);
    } finally {
      setIsProcessing(false);
    }
  };

  const handleFail = async () => {
    if (!selectedReason) return;
    setIsProcessing(true);
    try {
      await onStatusUpdate(withdrawalData.id, 'failed', selectedReason);
      onClose();
    } catch (error) {
      console.error('Error failing withdrawal:', error);
    } finally {
      setIsProcessing(false);
    }
  };

  const isLoading = userStatus === 'loading' || transactionsStatus === 'loading';

  return (
    <Dialog open={isOpen} onOpenChange={onClose}>
      <DialogContent className="max-w-2xl">
        <DialogHeader className="flex flex-row items-center justify-between">
          <DialogTitle>Withdrawal Request Details</DialogTitle>
          {!isLoading && (
            <PDFDownloadLink
              document={
                <WithdrawalSlip
                  withdrawalData={withdrawalData}
                  userData={{
                    firstName: userData?.firstName || '',
                    lastName: userData?.lastName || '',
                    email: userData?.email || '',
                    phoneNumber: userData?.phoneNumber || '',
                  }}
                />
              }
              fileName={`withdrawal-slip-${withdrawalData.reference}.pdf`}
            >
              {({ loading }) => (
                <Button
                  variant="outline"
                  size="sm"
                  className="gap-2 "
                  disabled={loading}
                >
                  <Printer className="h-4 w-4" />
                  Print Slip
                </Button>
              )}
            </PDFDownloadLink>
          )}
        </DialogHeader>

        {isLoading ? (
          <div className="flex justify-center items-center h-48">
            <Loader2 className="h-8 w-8 animate-spin" />
          </div>
        ) : (
          <div className="space-y-6">
            {/* User Information */}
            <div className="grid grid-cols-2 gap-4 p-4 bg-gray-50 rounded-lg">
              <div>
                <h3 className="font-semibold">User Information</h3>
                <p className="text-sm text-gray-600">Name: {userData?.firstName} {userData?.lastName}</p>
                <p className="text-sm text-gray-600">Email: {userData?.email}</p>
                <p className="text-sm text-gray-600">Phone: {userData?.phoneNumber}</p>
              </div>
              <div>
                <h3 className="font-semibold">Wallet Balance</h3>
                <p className="text-lg font-medium">
                  ₦{userData?.walletBalance.toLocaleString()}
                </p>
              </div>
            </div>

            {/* Withdrawal Details */}
            <div className="p-4 bg-gray-50 rounded-lg">
              <h3 className="font-semibold mb-2">Withdrawal Details</h3>
              <div className="grid grid-cols-2 gap-4">
                <div>
                  <p className="text-sm text-gray-600">Amount: ₦{withdrawalData.amount.toLocaleString()}</p>
                  <p className="text-sm text-gray-600">Bank: {withdrawalData.bankName}</p>
                  <p className="text-sm text-gray-600">Account: {withdrawalData.accountNumber}</p>
                  <p className="text-sm text-gray-600">Account Name: {withdrawalData.accountName}</p>
                </div>
                <div>
                  <p className="text-sm text-gray-600">Reference: {withdrawalData.reference}</p>
                </div>
              </div>
            </div>

            {/* Recent Transactions */}
            <div className="p-4 bg-gray-50 rounded-lg">
              <h3 className="font-semibold mb-2">Recent Transactions</h3>
              <div className="space-y-2">
                {recentTransactions?.map((transaction) => (
                  <div key={transaction.reference} className="flex justify-between text-sm">
                    <span>{new Date(transaction.date).toLocaleDateString()}</span>
                    <span className={transaction.type === 'withdrawal' ? 'text-red-600' : 'text-green-600'}>
                      {transaction.type === 'withdrawal' ? '-' : '+'}₦{transaction.amount.toLocaleString()}
                    </span>
                    <span className="capitalize">{transaction.status}</span>
                  </div>
                ))}
              </div>
            </div>

            {/* Action Buttons */}
            <div className="flex justify-between items-center pt-4">
              <div className="flex items-center gap-2">
                <Select onValueChange={setSelectedReason}>
                  <SelectTrigger className="w-[200px]">
                    <SelectValue placeholder="Select failure reason" />
                  </SelectTrigger> 
                  <SelectContent className="bg-white dark:bg-gray-800 border-0shadow-lg">
                    {FAILURE_REASONS.map((reason) => (
                      <SelectItem key={reason} value={reason}>
                        {reason}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
                <Button
                  variant="destructive"
                  onClick={handleFail}
                  disabled={!selectedReason || isProcessing}
                >
                  {isProcessing ? <Loader2 className="h-4 w-4 animate-spin" /> : 'Mark as Failed'}
                </Button>
              </div>
              <Button
                variant="default"
                onClick={handleComplete}
                disabled={isProcessing}
                className="bg-green-600 hover:bg-green-700 text-white"
              >
                {isProcessing ? <Loader2 className="h-4 w-4 animate-spin" /> : 'Complete Transfer'}
              </Button>
            </div>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}
