import React, { useState } from 'react';
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogFooter } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Mail, Phone, Shield, User } from 'lucide-react';

interface User {
  autoGeneratedId: string;
  nickname: string;
  email: string;
  emailVerified: boolean;
  phoneNumber: string;
  kycStatus: string;
  status: string;
  role: string;
}

interface UserEditFormProps {
  user: User;
  isOpen: boolean;
  onClose: () => void;
  onSubmit: (updatedUser: User) => void;
}

const UserEditForm: React.FC<UserEditFormProps> = ({ user, isOpen, onClose, onSubmit }) => {
  const [editedUser, setEditedUser] = useState<User>(user);

  const handleChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const { name, value } = e.target;
    setEditedUser(prev => ({ ...prev, [name]: value }));
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    onSubmit(editedUser);
    onClose();
  };

  return (
    <Dialog open={isOpen} onOpenChange={onClose}>
      <DialogContent className="sm:max-w-[525px] bg-white dark:bg-gray-800">
        <DialogHeader>
          <DialogTitle className="text-2xl font-bold text-gray-900 dark:text-white">Edit User Profile</DialogTitle>
        </DialogHeader>
        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <Label htmlFor="nickname" className="text-gray-700 dark:text-gray-300 flex items-center">
              <User className="mr-2 h-4 w-4" />
              Nickname
            </Label>
            <Input
              id="nickname"
              name="nickname"
              value={editedUser.nickname}
              onChange={handleChange}
              className="mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white"
            />
          </div>
          <div>
            <Label htmlFor="email" className="text-gray-700 dark:text-gray-300 flex items-center">
              <Mail className="mr-2 h-4 w-4" />
              Email
            </Label>
            <Input
              id="email"
              name="email"
              type="email"
              value={editedUser.email}
              onChange={handleChange}
              className="mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white"
            />
          </div>
          <div className="flex items-center space-x-2">
            <Switch
              id="emailVerified"
              checked={editedUser.emailVerified}
              onCheckedChange={(checked) => setEditedUser(prev => ({ ...prev, emailVerified: checked }))}
            />
            <Label htmlFor="emailVerified" className="text-gray-700 dark:text-gray-300">Email Verified</Label>
          </div>
          <div>
            <Label htmlFor="phoneNumber" className="text-gray-700 dark:text-gray-300 flex items-center">
              <Phone className="mr-2 h-4 w-4" />
              Phone Number
            </Label>
            <Input
              id="phoneNumber"
              name="phoneNumber"
              value={editedUser.phoneNumber}
              onChange={handleChange}
              className="mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white"
            />
          </div>
          <div>
            <Label htmlFor="kycStatus" className="text-gray-700 dark:text-gray-300 flex items-center">
              <Shield className="mr-2 h-4 w-4" />
              KYC Status
            </Label>
            <Select
              value={editedUser.kycStatus}
              onValueChange={(value) => setEditedUser(prev => ({ ...prev, kycStatus: value }))}
            >
              <SelectTrigger className="w-full mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white">
                <SelectValue placeholder="Select KYC status" />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="verified">Verified</SelectItem>
                <SelectItem value="pending">Pending</SelectItem>
                <SelectItem value="unverified">Unverified</SelectItem>
              </SelectContent>
            </Select>
          </div>
          <div>
            <Label htmlFor="status" className="text-gray-700 dark:text-gray-300">Account Status</Label>
            <Select
              value={editedUser.status}
              onValueChange={(value) => setEditedUser(prev => ({ ...prev, status: value }))}
            >
              <SelectTrigger className="w-full mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white">
                <SelectValue placeholder="Select account status" />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="active">Active</SelectItem>
                <SelectItem value="suspended">Suspended</SelectItem>
              </SelectContent>
            </Select>
          </div>
          <div>
            <Label htmlFor="role" className="text-gray-700 dark:text-gray-300">Role</Label>
            <Select
              value={editedUser.role}
              onValueChange={(value) => setEditedUser(prev => ({ ...prev, role: value }))}
            >
              <SelectTrigger className="w-full mt-1 bg-white dark:bg-gray-700 text-gray-900 dark:text-white">
                <SelectValue placeholder="Select user role" />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="user">User</SelectItem>
                <SelectItem value="admin">Admin</SelectItem>
              </SelectContent>
            </Select>
          </div>
          <DialogFooter>
            <Button type="button" variant="outline" onClick={onClose} className="dark:bg-gray-700 dark:text-white">
              Cancel
            </Button>
            <Button type="submit" className="bg-blue-500 hover:bg-blue-600 dark:bg-blue-600 dark:hover:bg-blue-700">
              Save Changes
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
};

export default UserEditForm;