import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Wallet, ArrowDownCircle, ArrowUpCircle, History, Bell, UserX, CreditCard, MinusCircle, LogIn, ClipboardList, Mail, Phone, Shield, Star, Calendar } from 'lucide-react';

