import React, { useState, useEffect } from 'react';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Button } from "@/components/ui/button";
import { Info } from 'lucide-react';
import siteData from '@/components/site-data.json';

interface User {
  autoGeneratedId: string;
  nickname: string;
  createdAt: string;
  walletBalance: number;
}

interface UserTableProps {
  onUserSelect: (user: User) => void;
}

const UserTable: React.FC<UserTableProps> = ({ onUserSelect }) => {
  const [users, setUsers] = useState<User[]>([]);

  useEffect(() => {
    setUsers(siteData.users);
  }, []);

  return (
    <Table>
      <TableHeader>
        <TableRow>
          <TableHead>Nickname</TableHead>
          <TableHead>Joined At</TableHead>
          <TableHead>Balance</TableHead>
          <TableHead>Action</TableHead>
        </TableRow>
      </TableHeader>
      <TableBody>
        {users.map((user) => (
          <TableRow key={user.autoGeneratedId}>
            <TableCell>{user.nickname}</TableCell>
            <TableCell>{new Date(user.createdAt).toLocaleDateString()}</TableCell>
            <TableCell>₦{user.walletBalance.toFixed(2)}</TableCell>
            <TableCell>
              <Button 
                variant="outline" 
                size="sm" 
                onClick={() => onUserSelect(user)}
              >
                <Info className="mr-2 h-4 w-4" />
                Details
              </Button>
            </TableCell>
          </TableRow>
        ))}
      </TableBody>
    </Table>
  );
};

export default UserTable;