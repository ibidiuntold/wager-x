'use client';

import React, { useEffect, useState } from 'react';
import { useSession } from 'next-auth/react';
import { doc, FirestoreDataConverter } from 'firebase/firestore';
import { cn } from "@/lib/utils";
import { UserProfile } from '@/types/user.types';
interface UserInfoProps {
  className?: string;
}

// Create a converter for UserProfile
const userProfileConverter: FirestoreDataConverter<UserProfile> = {
  toFirestore: (userProfile: UserProfile) => {
    return {
      autoGeneratedId: userProfile.autoGeneratedId,
      avatarUrl: userProfile.avatarUrl,
      createdAt: userProfile.createdAt,
      email: userProfile.email,
      emailVerified: userProfile.emailVerified,
      firstName: userProfile.firstName,
      lastName: userProfile.lastName,
      gamePoints: userProfile.gamePoints,
      referralCode: userProfile.referralCode,
      kycVerified: userProfile.kycVerified,
      lastLogin: userProfile.lastLogin,
      mailingSettings: userProfile.mailingSettings,
      nickname: userProfile.nickname,
      phoneNumber: userProfile.phoneNumber,
      role: userProfile.role,
      status: userProfile.status,
      walletBalance: userProfile.walletBalance,
      dob: userProfile.dob
    };
  },
  fromFirestore: (snapshot, options) => {
    const data = snapshot.data(options);
    return {
      autoGeneratedId: data.autoGeneratedId,
      avatarUrl: data.avatarUrl || '',
      createdAt: data.createdAt,
      email: data.email,
      emailVerified: data.emailVerified || false,
      firstName: data.firstName || '',
      lastName: data.lastName || '',
      gamePoints: data.gamePoints || 0,
      referralCode: data.referralCode || '',
      kycVerified: data.kycVerified || false,
      lastLogin: data.lastLogin,
      mailingSettings: {
        systemMessages: data.mailingSettings?.systemMessages ?? true,
        personalBonuses: data.mailingSettings?.personalBonuses ?? true,
        smsDistribution: data.mailingSettings?.smsDistribution ?? false,
        pushNotifications: data.mailingSettings?.pushNotifications ?? true,
      },
      nickname: data.nickname,
      phoneNumber: data.phoneNumber,
      role: data.role || 'user',
      status: data.status || 'active',
      walletBalance: data.walletBalance || 0,
      dob: data.dob || ''
    };
  },
};

export default function UserInfo() {
  const { data: session } = useSession();
  const user = session?.user;
  const [userData, setUserData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const fetchUserData = async () => {
      try {
        if (!user?.id) return;
        const res = await fetch(`/api/users?id=${user.id}`);
        if (res.ok) {
          const data = await res.json();
          setUserData(data.user || null);
        } else {
          setError('Failed to fetch user data');
        }
      } catch (err) {
        setError('Failed to fetch user data');
      } finally {
        setLoading(false);
      }
    };
    if (user?.id) fetchUserData();
  }, [user?.id]);

  if (loading) return <div>Loading user info...</div>;
  if (error) return <div>{error}</div>;

  return (
    <div>
      <h2>User Info</h2>
      <div>{userData?.name || user?.name}</div>
      {/* Render more user info here */}
    </div>
  );
}