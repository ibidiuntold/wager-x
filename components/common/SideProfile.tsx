import React, { memo } from 'react';
import { User, Copy, Settings } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { useToast } from "@/components/ui/use-toast";

interface UserDataType {
  id?: string;
  autoGeneratedId?: string;
  walletBalance: number;
  gamePoints: number;
}

interface ProfileProps {
  userData: UserDataType | null;
  isLoading: boolean;
}

const Profile: React.FC<ProfileProps> = memo(({ userData, isLoading }) => {
  const { toast } = useToast();

  const copyId = async () => {
    if (!userData?.id) return;

    try {
      if (navigator?.clipboard?.writeText) {
        await navigator.clipboard.writeText(userData.id);
      } else {
        // fallback for older browsers
        const textarea = document.createElement("textarea");
        textarea.value = userData.id;
        document.body.appendChild(textarea);
        textarea.select();
        document.execCommand("copy");
        document.body.removeChild(textarea);
      }

      toast({
        title: "ID Copied! ✅",
        description: "Your ID has been copied to clipboard.",
        duration: 1500,
      });
    } catch (err) {
      toast({
        title: "Copy Failed ❌",
        description: "Unable to copy ID. Please try again.",
        duration: 1500,
      });
    }
  };

  if (isLoading) {
    return <div className="animate-pulse h-8 bg-gray-200 dark:bg-gray-700 rounded" />;
  }

  return (
    <div className="flex items-center justify-between w-full ms-3">
      <div className="flex items-center space-x-2">
        <User className="h-5 w-5 text-gray-400 dark:text-gray-200" />
        <span className="text-sm font-medium text-gray-700 dark:text-gray-200">
          MY ID: {userData?.id ? `${userData.id.slice(0, 8)}...` : '...'} 
        </span>
        <Button 
          variant="ghost" 
          size="sm" 
          onClick={copyId}
          disabled={!userData?.id}
          className="hover:bg-gray-200 dark:hover:bg-gray-700 rounded-md p-2 transition-colors duration-200 text-gray-500 dark:text-gray-400"
        >
          <Copy className="h-4 w-4" />
        </Button>
      </div>
      {/* <Button 
        variant="ghost" 
        size="sm" 
        asChild
        className="hover:bg-gray-200 dark:hover:bg-gray-700 rounded-md p-2 transition-colors duration-200"
      >
        <a href="/profile">
          <Settings className="h-5 w-5" />
        </a>
      </Button> */}
    </div>
  );
});

export default Profile;
