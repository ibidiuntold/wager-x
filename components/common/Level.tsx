import React, { useState, memo } from 'react';
import { ChevronDown, ChevronUp } from 'lucide-react';
import Image from 'next/image';

interface GameLevel {
  name: string;
  requiredPoints: number;
}

interface UserDataType {
  id?: string;
  autoGeneratedId?: string;
  walletBalance: number;
  gamePoints: number;
}

interface UserLevelProps {
  userData: UserDataType | null;
  isLoading: boolean;
}

const GAME_LEVELS: GameLevel[] = [
  { name: 'Bronze', requiredPoints: 0 },
  { name: 'Silver', requiredPoints: 100 },
  { name: 'Gold', requiredPoints: 500 },
  { name: 'Platinum', requiredPoints: 1000 },
  { name: 'Diamond', requiredPoints: 5000 },
];

const UserLevelComponent: React.FC<UserLevelProps> = ({ userData, isLoading }) => {
  const [isExpanded, setIsExpanded] = useState(false);
  const gamePoints = userData?.gamePoints || 0;

  const getCurrentLevel = (points: number) => {
    // The GAME_LEVELS array is now defined directly in this file
    for (let i = GAME_LEVELS.length - 1; i >= 0; i--) {
      if (points >= GAME_LEVELS[i].requiredPoints) {
        return GAME_LEVELS[i].name;
      }
    }
    return GAME_LEVELS[0]?.name || 'Bronze';
  };

  const currentLevel = getCurrentLevel(gamePoints);
  const currentLevelIndex = GAME_LEVELS.findIndex(level => level.name === currentLevel);
  const progress = GAME_LEVELS.length ? ((currentLevelIndex + 1) / GAME_LEVELS.length) * 100 : 0;

  if (isLoading) {
    return <div className="animate-pulse h-24 bg-gradient-to-r from-purple-500 to-gray-100 dark:to-gray-800 rounded-lg" />;
  }

  return (
    <div className="bg-gradient-to-r from-purple-500 to-gray-100 dark:to-gray-800 rounded-lg p-4 mb-4 relative overflow-hidden">
      <Image
        src="/images/dice-one.svg"
        alt="Dice"
        fill
        className="opacity-30 object-cover"
      />
      <div className="relative z-10">
        <div className="flex justify-between items-center">
          <div className="flex-grow">
            {gamePoints > 0 ? (
              <>
                <span className="text-lg font-semibold text-gray-800 dark:text-white">
                  Points: {gamePoints} ({currentLevel})
                </span>
                <div className="mt-2 bg-white bg-opacity-30 dark:bg-gray-600 rounded-full h-2 overflow-hidden">
                  <div
                    className="bg-white dark:bg-purple-400 h-full rounded-full"
                    style={{ width: `${progress}%` }}
                  ></div>
                </div>
              </>
            ) : (
              <span className="text-lg font-semibold text-gray-800 dark:text-white">
                Start Earning Points
              </span>
            )}
          </div>
          <button
            onClick={() => setIsExpanded(!isExpanded)}
            className="p-1 rounded-full bg-white bg-opacity-30 dark:bg-gray-600 hover:bg-opacity-50 dark:hover:bg-opacity-75 text-gray-800 dark:text-white transition-colors duration-200"
            aria-label={isExpanded ? "Collapse level details" : "Expand level details"}
          >
            {isExpanded ? (
              <ChevronUp className="h-6 w-6" />
            ) : (
              <ChevronDown className="h-6 w-6" />
            )}
          </button>
        </div>
        {isExpanded && (
          <div className="mt-4 space-y-2 bg-white/30 dark:bg-gray-700/30 rounded-xl p-4">
            {gamePoints > 0 ? (
              <>
                <h3 className="text-md font-semibold text-gray-800 dark:text-white">Game Levels:</h3>
                {GAME_LEVELS.map((level, index) => (
                  <p
                    key={level.name}
                    className={`text-sm ${index <= currentLevelIndex
                        ? 'text-gray-600 dark:text-gray-400 line-through'
                        : 'text-gray-800 dark:text-gray-200'
                      }`}
                  >
                    {index + 1}. {level.name} (Required Points: {level.requiredPoints})
                  </p>
                ))}
              </>
            ) : (
              <>
                <h3 className="text-md font-semibold text-gray-800 dark:text-white">How to Earn Points:</h3>
                <ul className="list-disc pl-5">
                  <li className="text-sm text-gray-800 dark:text-gray-200">Play games to earn points</li>
                  <li className="text-sm text-gray-800 dark:text-gray-200">Win matches to earn bonus points</li>
                  <li className="text-sm text-gray-800 dark:text-gray-200">Complete daily tasks</li>
                  <li className="text-sm text-gray-800 dark:text-gray-200">Invite friends to join</li>
                  <li className="text-sm text-gray-800 dark:text-gray-200">Participate in tournaments</li>
                </ul>
              </>
            )}
          </div>
        )}
      </div>
    </div>
  );
};

const UserLevel = memo(UserLevelComponent);
export default UserLevel;
