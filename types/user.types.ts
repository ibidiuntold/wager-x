export type UserRole = 'user' | 'admin';
export type UserStatus = 'active' | 'inactive' | 'suspended' | 'banned' | 'pending';

export interface MailingSettings {
  personalBonuses: boolean;
  pushNotifications: boolean;
  smsDistribution: boolean;
  systemMessages: boolean;
}

export interface UserProfile {
  autoGeneratedId: string;
  avatarUrl: string;
  createdAt: string;
  email: string;
  emailVerified: boolean;
  firstName: string;
  lastName: string;
  nickname: string;
  dob: string;
  gamePoints: number;
  referralCode: string;
  kycVerified: boolean;
  lastLogin: string;
  mailingSettings: MailingSettings;
  phoneNumber: string | null;
  role: UserRole;
  status: UserStatus;
  walletBalance: number;
}

export interface UserData extends UserProfile {
  id?: string;
  lastUpdated: string;
  bankDetails?: {
    accountNumber: string;
    bankCode: string;
    bankName: string;
    accountName: string;
  };
}

export interface UserSignUpData {
  email: string;
  password: string;
  firstName: string;
  lastName: string;
  dob: string;
  nickname: string;
  phone: string;
}

export interface GoogleSignUpData {
  firstName: string;
  lastName: string;
  dob: string;
  nickname: string;
  phoneNumber: string;
}

export interface UserUpdateData {
  firstName?: string;
  lastName?: string;
  nickname?: string;
  phoneNumber?: string;
  avatarUrl?: string;
  mailingSettings?: Partial<MailingSettings>;
}

export interface UserStats {
  totalWagers: number;
  winRate: number;
  favoriteGames: string[];
  lastActive: string;
  totalWinnings: number;
  rank: number;
  level: number;
  xp: number;
}

export interface UserNotificationSettings {
  email: boolean;
  push: boolean;
  sms: boolean;
  gameAlerts: boolean;
  promotionalOffers: boolean;
  securityAlerts: boolean;
}

export interface UserKYCData {
  verified: boolean;
  submittedAt?: string;
  verifiedAt?: string;
  documents: {
    idCard?: string;
    proofOfAddress?: string;
    selfie?: string;
  };
  status: 'pending' | 'verified' | 'rejected' | 'not_submitted';
}

export interface UserWalletData {
  balance: number;
  transactions: Array<{
    id: string;
    type: 'deposit' | 'withdrawal' | 'bonus' | 'wager' | 'win';
    amount: number;
    timestamp: string;
    status: 'pending' | 'completed' | 'failed';
    reference?: string;
  }>;
  depositLimit: {
    daily: number;
    weekly: number;
    monthly: number;
  };
}

export interface UserPreferences {
  theme: 'light' | 'dark' | 'system';
  language: string;
  timezone: string;
  currency: string;
  odds: 'decimal' | 'fractional' | 'american';
}